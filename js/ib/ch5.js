  /* ---- the overview: the cycle as a diagram of the order of its steps (seat 0, oxaloacetate, at the top left; clockwise,
     the acetyl group entering at the top); each name in the first place where it touches no other name, no arrow and
     no line (Daniel: "Make sure that labels do not overlap") ---- */
  const NS = 'http://www.w3.org/2000/svg', ovEl = document.createElement('div'); ovEl.className = 'ibv__ovin ibv__ovin--cycle';
  const svg = document.createElementNS(NS, 'svg'); svg.setAttribute('class', 'ibv__ovsvg'); ovEl.appendChild(svg);
  const mk = cls => tag => { const e = document.createElementNS(NS, tag); e.setAttribute('class', cls); svg.appendChild(e); return e; };
  const arcEl = STEPS.map(() => mk('ibv__ova')('path')), headEl = STEPS.map(() => mk('ibv__ovah')('path')), lineEl = STEPS.map(() => mk('ibv__ovl')('line'));
  const seatDot = SEATS.map(() => mk('ibv__ovsd')('circle'));
  const seatEl = SEATS.map(([, name, nC, ib]) => { const e = document.createElement('span'); e.className = 'ibv__ovk' + (ib ? ' is-ib' : ''); e.innerHTML = (ib ? name : `<i>${name}</i>`) + `<b>${nC}</b>`; ovEl.appendChild(e); return e; });
  /* what enters and leaves: each item kept whole on a line ("CO₂ out", never "CO₂" / "out") */
  const items = ex => ex.split(' · ').map(s => s.replace(/ /g, '&nbsp;')).join(' · ');
  const stepEl = STEPS.map(([enz, ex]) => { const e = document.createElement('span'); e.className = 'ibv__ovn ibv__ovn--k'; e.innerHTML = `<i>${enz}</i>` + (ex ? `<small>${items(ex)}</small>` : ''); ovEl.appendChild(e); return e; });
  const dot = document.createElement('i'); dot.className = 'ibv__ovd'; dot.hidden = true; ovEl.appendChild(dot);
  /* a phone: the two molecules of the step at work, beside the small ring */
  const pairEl = document.createElement('div'); pairEl.className = 'ibv__ovp'; pairEl.hidden = true; ovEl.appendChild(pairEl);
  const seatHtml = i => { const [, name, nC, ib] = SEATS[i % 8]; return `<b class="${ib ? 'is-ib' : ''}">${ib ? name : `<i>${name}</i>`}<em>${nC}</em></b>`; };
  const seatA = i => Math.PI / 2 + Math.PI / 8 - i * Math.PI / 4;
  let laid = '', ring = null;
  function layoutOv(B, narrow) {
    if (narrow) return layoutPhone(B);
    pairEl.hidden = true;
    const W = B.W, H = B.H, cx = W / 2, cy = H / 2 + 2, rx = Math.min(W * 0.27, 300), ry = H * 0.29;
    const pt = a => [cx + rx * Math.cos(a), cy - ry * Math.sin(a)];
    const placed = [], gap = 6, boxOf = [];
    const touches = b => placed.some(o => b.l < o.r + gap && b.r > o.l - gap && b.t < o.b + 3 && b.b > o.t - 3);
    const crosses = (x0, y0, x1, y1) => placed.some(o => { for (let k = 1; k < 10; k++) { const px = x0 + (x1 - x0) * k / 10, py = y0 + (y1 - y0) * k / 10; if (px > o.l && px < o.r && py > o.t && py < o.b) return true; } return false; });
    /* the seats: the molecule's name on the ring */
    SEATS.forEach((s, i) => {
      const e = seatEl[i], [x, y] = pt(seatA(i)), on = true;
      seatDot[i].setAttribute('cx', x.toFixed(1)); seatDot[i].setAttribute('cy', y.toFixed(1)); seatDot[i].setAttribute('r', '3.5');
      e.hidden = !on;
      if (!on) { boxOf[i] = { l: x - 5, r: x + 5, t: y - 5, b: y + 5 }; return; }
      const w = e.offsetWidth, h = e.offsetHeight, b = { l: x - w / 2, r: x + w / 2, t: y - h / 2, b: y + h / 2 };
      e.style.transform = `translate(${b.l.toFixed(1)}px, ${b.t.toFixed(1)}px)`; placed.push(b); boxOf[i] = b;
    });
    /* the arrows, from the edge of one seat's name to the next, clockwise */
    const leave = (a, b, dir) => { let k = 0; for (; k < 500; k++) { const [x, y] = pt(a + dir * k * 0.004); if (x < b.l - 4 || x > b.r + 4 || y < b.t - 4 || y > b.b + 4) break; } return a + dir * k * 0.004; };
    STEPS.forEach((s, i) => {
      const a0 = leave(seatA(i), boxOf[i], -1), tip = leave(seatA(i + 1), boxOf[(i + 1) % 8], 1);
      const sp = Math.hypot(rx * Math.sin(tip), ry * Math.cos(tip)), a1 = tip + 9 / sp;
      const [x0, y0] = pt(a0), [x1, y1] = pt(a1), [tx, ty] = pt(tip);
      arcEl[i].setAttribute('d', `M${x0.toFixed(1)} ${y0.toFixed(1)}A${rx.toFixed(1)} ${ry.toFixed(1)} 0 0 1 ${x1.toFixed(1)} ${y1.toFixed(1)}`);
      const vx = rx * Math.sin(tip), vy = ry * Math.cos(tip), ux = vx / sp, uy = vy / sp;
      headEl[i].setAttribute('d', `M${tx.toFixed(1)} ${ty.toFixed(1)}L${(tx - ux * 9 - uy * 5).toFixed(1)} ${(ty - uy * 9 + ux * 5).toFixed(1)}L${(tx - ux * 9 + uy * 5).toFixed(1)} ${(ty - uy * 9 - ux * 5).toFixed(1)}Z`);
    });
    /* the ring, where no name may stand (but the seats' own) */
    const rp = []; for (let k = 0; k < 160; k++) { const [x, y] = pt(k / 160 * 2 * Math.PI); if (!placed.some(o => x > o.l && x < o.r && y > o.t && y < o.b)) rp.push([x, y]); }
    const onRing = b => rp.some(([x, y]) => x > b.l - 4 && x < b.r + 4 && y > b.t - 4 && y < b.b + 4);
    /* each step's enzyme, and what enters and leaves it: beside its arrow, outside the ring first, a line to the arrow;
       the steps with least room first (top and bottom) */
    for (const i of [0, 4, 1, 7, 3, 5, 2, 6]) {
      const e = stepEl[i], ln = lineEl[i];
      e.hidden = false; ln.style.display = '';
      const w = e.offsetWidth, h = e.offsetHeight, m = seatA(i) - Math.PI / 8, [ax, ay] = pt(m);
      let nx = Math.cos(m) / rx, ny = -Math.sin(m) / ry; const nl = Math.hypot(nx, ny); nx /= nl; ny /= nl;
      let got = null;
      search: for (const dir of [1, -1]) for (const d of [8, 18, 30, 44, 60]) for (const s of [0, -24, 24, -48, 48, -72, 72, -100, 100]) {
        const k = d + (w * Math.abs(nx) + h * Math.abs(ny)) / 2, bx = ax + dir * nx * k - ny * s, by = ay + dir * ny * k + nx * s;
        const b = { l: bx - w / 2, r: bx + w / 2, t: by - h / 2, b: by + h / 2 };
        if (b.l < 4 || b.r > W - 4 || b.t < 2 || b.b > H - 2 || touches(b) || onRing(b)) continue;
        const dx = ax - bx, dy = ay - by, f = Math.min(Math.abs(dx) > 1e-6 ? (w / 2) / Math.abs(dx) : 1e9, Math.abs(dy) > 1e-6 ? (h / 2) / Math.abs(dy) : 1e9);
        if (f >= 1) continue;
        const ex = bx + dx * f, ey = by + dy * f;
        if (crosses(ex, ey, ax, ay)) continue;
        got = { b, ex, ey }; break search;
      }
      if (!got) { e.hidden = true; ln.style.display = 'none'; continue; }
      placed.push(got.b);
      e.style.transform = `translate(${got.b.l.toFixed(1)}px, ${got.b.t.toFixed(1)}px)`;
      ln.setAttribute('x1', got.ex.toFixed(1)); ln.setAttribute('y1', got.ey.toFixed(1)); ln.setAttribute('x2', ax.toFixed(1)); ln.setAttribute('y2', ay.toFixed(1));
    }
    ring = pt;
  }
  /* a phone: a small ring of the eight seats at the left (the arrow of the step at work lit, the gold dot), and beside it
     the two molecules of that step, its enzyme and what enters and leaves it */
  function layoutPhone(B) {
    const W = B.W, H = B.H, R = Math.min(H * 0.34, 40), cx = 14 + R, cy = H / 2 + 1;
    const pt = a => [cx + R * Math.cos(a), cy - R * Math.sin(a)];
    seatEl.forEach(e => { e.hidden = true; }); lineEl.forEach(l => { l.style.display = 'none'; });
    SEATS.forEach((s, i) => { const [x, y] = pt(seatA(i)); seatDot[i].setAttribute('cx', x.toFixed(1)); seatDot[i].setAttribute('cy', y.toFixed(1)); seatDot[i].setAttribute('r', '3'); });
    STEPS.forEach((s, i) => {
      const g0 = 7 / R, a0 = seatA(i) - g0, tip = seatA(i + 1) + g0, a1 = tip + 6 / R;
      const [x0, y0] = pt(a0), [x1, y1] = pt(a1), [tx, ty] = pt(tip), ux = Math.sin(tip), uy = Math.cos(tip);
      arcEl[i].setAttribute('d', `M${x0.toFixed(1)} ${y0.toFixed(1)}A${R.toFixed(1)} ${R.toFixed(1)} 0 0 1 ${x1.toFixed(1)} ${y1.toFixed(1)}`);
      headEl[i].setAttribute('d', `M${tx.toFixed(1)} ${ty.toFixed(1)}L${(tx - ux * 6 - uy * 3.5).toFixed(1)} ${(ty - uy * 6 + ux * 3.5).toFixed(1)}L${(tx - ux * 6 + uy * 3.5).toFixed(1)} ${(ty - uy * 6 - ux * 3.5).toFixed(1)}Z`);
    });
    const x0 = cx + R + 16, wmax = W - x0 - 8;
    pairEl.hidden = false; pairEl.style.maxWidth = wmax + 'px';
    pairEl.innerHTML = ovCur == null ? seatHtml(0) : seatHtml(ovCur) + '<span>→</span>' + seatHtml(ovCur + 1);
    const se = ovCur == null ? null : stepEl[ovCur];
    stepEl.forEach(e => { e.hidden = e !== se; });
    if (se) se.style.maxWidth = wmax + 'px';
    const ph = pairEl.offsetHeight, sh = se ? se.offsetHeight + 6 : 0, top = Math.max(4, (H - ph - sh) / 2);
    pairEl.style.transform = `translate(${x0.toFixed(1)}px, ${top.toFixed(1)}px)`;
    if (se) se.style.transform = `translate(${x0.toFixed(1)}px, ${(top + ph + 6).toFixed(1)}px)`;
    ring = pt;
  }
  function placeOv(P, B) {
    const narrow = B.W < 560, key = B.W + 'x' + B.H + (narrow ? ':' + ovCur : '');
    ovEl.classList.toggle('is-narrow', narrow);
    STEPS.forEach((s, i) => { const on = i === ovCur; [stepEl[i], lineEl[i], arcEl[i], headEl[i]].forEach(e => e.classList.toggle('is-on', on)); });
    if (key !== laid) { laid = key; layoutOv(B, narrow); }
    /* the gold dot: where the molecule is, along the arrow of the step at work; at a seat, on that seat's name, which glows
       (css .ibv__ovk.is-at) */
    const w8 = ((ovW % 8) + 8) % 8, at = Math.abs(ovW - Math.round(ovW)) < 0.03, si = Math.round(w8) % 8;
    seatEl.forEach((e, i) => e.classList.toggle('is-at', at && i === si));
    /* on a phone the molecule's seat is a dot of the small ring: the gold dot stays on it */
    dot.hidden = (at && !narrow) || !ring;
    if (!dot.hidden) { const [x, y] = ring(seatA(0) - w8 * Math.PI / 4); dot.style.transform = `translate(${(x - 6).toFixed(1)}px, ${(y - 6).toFixed(1)}px)`; }
  }
  const overview = { el: ovEl, place: placeOv, frac: 0.36, fracN: 0.3, max: 300 };
  /* every atom on the screen, which no name may cover (stage.js setAvoid) */
  const avoid = () => drawn.atoms.filter(a => a.s == null || a.s > 0.5).map(a => ({ p: a.p, id: a.id, h: a.el === 'H' }));
  return { group: g, knobs, views, steps, labels, draw, nums, avoid, overview, turn: true, dispose() { BS.dispose(); disposeGroup(g); } };
