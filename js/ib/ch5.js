/* ============================================================
   ch5.js — chapter 5, the Krebs cycle in the matrix (5 Nov 2026). Daniel: "make sure that the Krebs cycle, you know, it's
   beautifully displayed". IB C1.2.12: "name only the intermediates citrate (6C) and oxaloacetate (4C) ... citrate is
   produced by transfer of an acetyl group to oxaloacetate ... oxaloacetate is regenerated by the reactions of the Krebs
   cycle, including four oxidations and two decarboxylations ... the oxidations are dehydrogenation reactions."
   A wheel: the eight molecules of the cycle at its seats (the wheel is a diagram of the ORDER of the steps; in the matrix
   the molecules are not in a ring: the chapter says so), each named with its number of carbon atoms; the wheel turns to
   bring each step to the top, where the reaction happens: the real atoms move (mol.js Reaction), the carbon dioxide, NADH,
   FADH₂ and ATP leave outwards, and counters keep the tally. FAD works inside complex II (succinate dehydrogenase), an
   enzyme of the inner membrane (PDB 8GS8), which hangs above the wheel's top seat for that step.
   Glucose's carbons are followed exactly, by the atoms (the mapping is in the moves below, from the enzymes' known
   chemistry: citrate synthase joins acetyl's methyl carbon to oxaloacetate's C2; aconitase moves the OH to the carbon
   from oxaloacetate's C3; isocitrate dehydrogenase releases the carboxyl from oxaloacetate's C1; α-ketoglutarate
   dehydrogenase releases the one from oxaloacetate's C4; Krebs and Lowenstein 1960; Berg, Tymoczko and Stryer 2019, §17).
   So the two carbon dioxide molecules of a turn are carbons that entered in an EARLIER turn (grey); the acetyl's carbons
   (glucose's 5 and 6) stay, in the oxaloacetate made again; in the second turn glucose's carbon 5 leaves. Succinate is
   symmetrical, so in a cell either end of it can carry the labelled carbons; the picture follows one of the two (equally
   likely) ways.
   ============================================================ */
