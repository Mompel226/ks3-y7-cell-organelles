    succ: { html: '<i>succinate</i> (4C)', side: 'l', lv: 'x', pts: molPts('o') },
    fum: { html: '<i>fumarate</i> (4C)', side: 'l', lv: 'x', pts: molPts('o') },
    mal: { html: '<i>malate</i> (4C)', side: 'l', lv: 'x', pts: molPts('o') },
    co2: { html: 'carbon dioxide', side: 'l', pts: molPts('x') },
    nadh: { html: 'NADH', side: 'r', pts: molPts('n', nicot) },
    scoa: { html: '<i>succinyl CoA</i> (4C)', side: 'l', lv: 'x', pts: molPts('c', ['A1', 'A2', 'A3', 'A4', 'S']) },
